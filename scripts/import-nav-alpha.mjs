// Regenerates src/data/catalog-data.js from a nav-alpha MechDB mech dump.
//
//   1. Get the data: either log in at https://mwo.nav-alpha.com, create an API key, and run
//        curl -X POST -H "Authorization: Bearer YOUR_KEY" -H "Content-Type: application/json" \
//             -d '{}' https://mwo.nav-alpha.com/api/mechs/ -o mechs.json
//      or save the /api/mechs/ response from your browser's dev tools (Network tab) as mechs.json.
//   2. node scripts/import-nav-alpha.mjs mechs.json
import fs from 'node:fs';

const file = process.argv[2];
if (!file) {
  console.error('Usage: node scripts/import-nav-alpha.mjs mechs.json');
  process.exit(1);
}
const rows = JSON.parse(fs.readFileSync(file, 'utf8')).data;

const WORDS = {
  iic: 'IIC', ii: 'II', mk: 'Mk', ku: 'KU', battlemaster: 'BattleMaster', jagermech: 'JagerMech',
  urbanmech: 'UrbanMech', shadowhawk: 'Shadow Hawk', firemoth: 'Fire Moth', madcat: 'Mad Cat',
  'hatamoto-chi': 'Hatamoto-Chi',
};
function chassisName(raw) {
  const fixed = raw.replace(/^clan(?=[a-z])/, 'clan ');
  return fixed
    .split(' ')
    .map((w) => WORDS[w] || w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

// nav-alpha's internal names end in "lgd" for Legendary mechs (MOONWALKER is "mcii-mwklgd").
// A "(L)" suffix is a Loyalty reward mech, not a Legendary.
const isLegendary = (r) => /\(?lgd\)?$/.test(r.name);
const legendaryBases = new Set(rows.filter(isLegendary).map((r) => r.name.replace(/\(?lgd\)?$/, '')));

function kindOf(r) {
  const name = r.display_name.toUpperCase();
  if (isLegendary(r)) return 'legendary';
  if (r.type === 'hero') return 'hero';
  if (r.type === 'champion') return 'champion';
  if (/\(L\)$/.test(name)) return 'loyalty';
  if (r.type) return 'special';
  return r.omni === '1' ? 'omni' : 'standard';
}

// Tournament Supporter Pack mechs show in-game as "TBR-M(TSP)"; nav-alpha writes "TBR-MTS(P)".
function tspName(code) {
  const m = code.match(/^(.*)TS\(P\)$/);
  return m ? `${m[1]}(TSP)` : null;
}

const byChassis = new Map();
for (const r of rows) {
  const chassis = chassisName(r.chassis);
  if (!byChassis.has(chassis)) {
    byChassis.set(chassis, { chassis, tons: Number(r.tonnage), tech: r.faction === 'clan' ? 'CL' : 'IS', variants: [] });
  }
  let code = r.display_name.toUpperCase().trim();
  let alias;
  const tsp = tspName(code);
  if (tsp) {
    alias = code;
    code = tsp;
  } else if (/\(TSP\)$/.test(code)) {
    alias = code.replace(/\(TSP\)$/, 'TS(P)');
  } else if (r.type === 'hero' && r.name.toUpperCase() !== code) {
    // Heroes show a name ("HUGINN"); keep the short code ("RVN-H") as an alias for pasted text.
    alias = r.name.toUpperCase();
  }
  const kind = kindOf(r);
  // Hero versions of Legendaries (hero PXH-S vs Legendary PXH-S(LGD)); most tournaments ban both.
  const lgdHero = kind === 'hero' && legendaryBases.has(r.name) ? 1 : 0;
  const entry = [code, kind];
  if (alias || lgdHero) entry.push(alias || null);
  if (lgdHero) entry.push(1);
  byChassis.get(chassis).variants.push(entry);
}

const list = [...byChassis.values()].sort((a, b) => a.tons - b.tons || a.chassis.localeCompare(b.chassis));
const lines = list.map((c) => `  [${JSON.stringify(c.chassis)}, ${c.tons}, '${c.tech}', ${JSON.stringify(c.variants)}],`);
const out = `// Generated by scripts/import-nav-alpha.mjs from nav-alpha MechDB (${new Date().toISOString().slice(0, 10)}).
// ${rows.length} variants across ${list.length} chassis. Edit in the app (Mech Catalog) rather than here.
// Row: [chassis, tons, tech, [[code, kind, alias?, legendaryHero?], ...]]
export const CATALOG_ROWS = [
${lines.join('\n')}
];
`;
fs.writeFileSync(new URL('../src/data/catalog-data.js', import.meta.url), out);
console.log(`Wrote ${rows.length} variants, ${list.length} chassis.`);
